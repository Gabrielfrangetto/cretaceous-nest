// Writes docs/COMBAT.md: who can hurt whom, from each species' weapon (bite) and hide in config.js.
// Worst case for the defender: the attacker with perfect genes and its hardest roll, against the
// defender with the weakest genes. Run it after changing BODY: node scripts/matchups.js
import { writeFileSync } from 'node:fs';
import { SPECIES, ORDER, GENES_MAX } from '../js/config.js';
import { fighterOf, hitOf } from '../js/combat.js';

const at = (type, g) => fighterOf({ id: type, type, name: type, genes: { str: g, agi: g, vit: g, res: g }, equip: {}, fed: 0 });
// the most one blow can take off, as a share of the defender's health
export function bestBlow(a, b) {
  const att = at(a, GENES_MAX), def = at(b, 0);
  return { dmg: Math.round(hitOf(att, def, 1.25)), share: hitOf(att, def, 1.25) / def.hp };
}
// none: it can't hurt it at all; scratch: under 3% of its health a blow; wound: more
export const level = ({ dmg, share }) => !dmg ? 'none' : share < 0.03 ? 'scratch' : 'wound';
const MARK = { none: '·', scratch: '~', wound: '✓' };

const name = t => SPECIES[t].species;
let md = `# Who can hurt whom\n\nGenerated by \`node scripts/matchups.js\` from the weapons and hides in \`js/config.js\` (BODY).\n` +
  `Worst case for the defender: the attacker has perfect genes and lands its hardest blow, the defender has the weakest genes.\n\n` +
  `## Weapons, hides and roles\n\nRole: attacker (goes for the foe), defender (charges or holds its ground and strikes back) or noncombatant (only strikes back, or through an opening); see config.js. Runs from: it flees, before the fight, from anything bigger than this.\n\n| Species | Size | Weapon | Strongest blow | Hide | Role | Stands up to |\n|---|---|---|---|---|---|---|\n` +
  ORDER.map(t => `| ${name(t)} | ${SPECIES[t].size} | ${SPECIES[t].weapon} | ${SPECIES[t].bite} | ${SPECIES[t].hide} | ${SPECIES[t].role} | ${SPECIES[t].fear} |`).join('\n') +
  `\n\n## Who each one can't hurt\n\n`;
for (const a of ORDER) {
  const none = ORDER.filter(b => level(bestBlow(a, b)) === 'none').map(name);
  const scratch = ORDER.filter(b => level(bestBlow(a, b)) === 'scratch').map(name);
  md += `- **${name(a)}**: ${none.length ? 'can\'t hurt ' + none.join(', ') : 'can hurt every species'}` +
    `${scratch.length ? `; only scratches ${scratch.join(', ')}` : ''}.\n`;
}
md += `\n## Grid\n\nRows attack, columns defend. ✓ wounds, ~ only scratches (under 3% of its health a blow), · can't hurt.\n\n` +
  `| | ${ORDER.map(t => t).join(' | ')} |\n|---|${ORDER.map(() => '---').join('|')}|\n` +
  ORDER.map(a => `| **${a}** | ${ORDER.map(b => MARK[level(bestBlow(a, b))]).join(' | ')} |`).join('\n') + '\n';
writeFileSync(new URL('../docs/COMBAT.md', import.meta.url), md);
console.log(md.slice(md.indexOf('## Who'), md.indexOf('## Grid')));
